import assert from 'node:assert/strict';
import {priceFor,marginFor,applyRules,validateRules,charmRound} from './pricing.mjs';
const p=priceFor({cost:10,shipping:4,feeRate:0.029,feeFixed:0.3,refundReserveRate:0.02,targetMargin:0.4});
assert.equal(p.cents,2599);assert.equal(p.breakdown.cost,1000);assert.equal(p.breakdown.shipping,400);
const m=marginFor({retail:29.99,cost:10,shipping:4,feeRate:0.029,feeFixed:0.3,refundReserveRate:0.02});
assert.ok(m.margin>0.47&&m.margin<0.48);
assert.equal(charmRound(1000),999);assert.equal(charmRound(2500),2599);assert.equal(charmRound(99),99);
assert.equal(charmRound(150000,'ngn'),149900);
const applied=applyRules({cost:20,shipping:5,rules:{targetMargin:0.4,feeRate:0.029,feeFixed:0.3,refundReserveRate:0.02,currency:'USD'}});
assert.equal(applied.meetsFloor,true);assert.equal(applied.retail,applied.cents/100);
const ngn=applyRules({cost:5000,shipping:1500,rules:{targetMargin:0.35,currency:'NGN'}});
assert.equal(ngn.cents%10000,9900);
assert.throws(()=>priceFor({cost:10,targetMargin:1}),e=>e.status===422);
assert.throws(()=>priceFor({cost:10,targetMargin:0}),e=>e.status===422);
assert.throws(()=>priceFor({cost:-1,targetMargin:0.4}),e=>e.status===422);
assert.throws(()=>validateRules({currency:'EUR'}),e=>e.status===422);
assert.equal(validateRules({}).targetMargin,0.4);
assert.throws(()=>marginFor({retail:0,cost:1}),e=>e.status===422);
console.log('PASS: margin engine arithmetic, charm rounding (USD/NGN), floor checks, invalid inputs rejected.');
